import { promises as fs } from "fs";
import path from "path";
import type { NextApiRequest, NextApiResponse } from "next";

import { UPLOADS_DIR } from "@/lib/screenStore";

// Serves background images uploaded in /admin when running self-hosted
// (filesystem storage). On Vercel, uploads live in Vercel Blob and are
// served from its own public URLs instead.
const TYPES: Record<string, string> = {
  jpg: "image/jpeg",
  png: "image/png",
  webp: "image/webp",
};

export default async function handler(req: NextApiRequest, res: NextApiResponse) {
  const file = String(req.query.file || "");
  const ext = file.split(".").pop() || "";
  // Names are generated by saveUpload; reject anything else (no path tricks).
  if (!/^[a-z0-9-]+\.(jpg|png|webp)$/.test(file) || !TYPES[ext]) {
    return res.status(404).end();
  }
  try {
    const data = await fs.readFile(path.join(UPLOADS_DIR, file));
    res.setHeader("Content-Type", TYPES[ext]);
    res.setHeader("Cache-Control", "public, max-age=31536000, immutable");
    return res.status(200).send(data);
  } catch {
    return res.status(404).end();
  }
}
